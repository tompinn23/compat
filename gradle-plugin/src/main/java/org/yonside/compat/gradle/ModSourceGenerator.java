package org.yonside.compat.gradle;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Writes the Java source of a mod's {@code @Mod} class and event listener for one Minecraft version,
 * for the class annotated {@code @CompatMod}. The version project compiles it like its own code, against
 * Minecraft and Forge in dev names, and RFG or Loom maps it to production names with the rest of the jar.
 *
 * <p>The listener is a separate class from the mod so that, on 1.16.5, mod-bus and Forge-bus handlers
 * never share an object.
 */
final class ModSourceGenerator {

    private ModSourceGenerator() {}

    /** Generated classes sit beside the addon class. No {@code $}: 1.7.10 and 1.12.2 do not scan such names. */
    static String modClassName(String addonInternalName) {
        return simpleName(addonInternalName) + "ForgeMod";
    }

    static String listenerClassName(String addonInternalName) {
        return simpleName(addonInternalName) + "ForgeEvents";
    }

    /** Source path inside the generated source root to file contents. */
    static Map<String, String> generate(MinecraftTarget target, String addonInternalName, String modId, String dependencies) {
        int slash = addonInternalName.lastIndexOf('/');
        String packageName = slash < 0 ? "" : addonInternalName.substring(0, slash).replace('/', '.');
        String packagePath = slash < 0 ? "" : addonInternalName.substring(0, slash + 1);
        Context ctx = new Context(target, packageName, addonInternalName.replace('/', '.').replace('$', '.'),
            modClassName(addonInternalName), listenerClassName(addonInternalName), modId, dependencies);

        Map<String, String> files = new LinkedHashMap<>();
        files.put(packagePath + ctx.modClass + ".java", modClass(ctx));
        files.put(packagePath + ctx.listenerClass + ".java", listenerClass(ctx));
        return files;
    }

    private record Context(MinecraftTarget target, String packageName, String addonClass, String modClass,
                           String listenerClass, String modId, String dependencies) {

        String header() {
            return "// Generated by the org.yonside.compat.addon Gradle plugin for Minecraft " + target.version
                + ". Do not edit.\n" + (packageName.isEmpty() ? "" : "package " + packageName + ";\n") + "\n";
        }
    }

    private static String modClass(Context ctx) {
        StringBuilder out = new StringBuilder(ctx.header());
        switch (ctx.target.loader) {
            case CPW -> legacyMod(out, ctx, "cpw.mods.fml.common.Mod", "cpw.mods.fml.common.event.FMLInitializationEvent");
            case FML -> legacyMod(out, ctx, "net.minecraftforge.fml.common.Mod",
                "net.minecraftforge.fml.common.event.FMLInitializationEvent");
            case FORGE -> forgeMod(out, ctx);
        }
        return out.toString();
    }

    private static void legacyMod(StringBuilder out, Context ctx, String modAnnotation, String initEvent) {
        out.append("import ").append(modAnnotation).append(";\n");
        out.append("import ").append(initEvent).append(";\n");
        out.append("import net.minecraftforge.common.MinecraftForge;\n");
        out.append("import org.yonside.compat.api.CompatAddon;\n\n");

        out.append("@Mod(\n");
        out.append("    modid = ").append(literal(ctx.modId)).append(",\n");
        out.append("    useMetadata = true,\n");
        out.append("    acceptedMinecraftVersions = ").append(literal("[" + ctx.target.version + "]"));
        if (!ctx.dependencies.isEmpty()) {
            out.append(",\n    dependencies = ").append(literal(ctx.dependencies));
        }
        out.append("\n)\n");
        out.append("public final class ").append(ctx.modClass).append(" {\n\n");
        out.append("    private final CompatAddon addon = new ").append(ctx.addonClass).append("();\n\n");
        out.append("    public ").append(ctx.modClass).append("() {\n");
        out.append("        MinecraftForge.EVENT_BUS.register(new ").append(ctx.listenerClass).append("(addon));\n");
        out.append("    }\n\n");
        out.append("    @Mod.EventHandler\n");
        out.append("    public void init(FMLInitializationEvent event) {\n");
        out.append("        addon.onInit();\n");
        out.append("    }\n");
        out.append("}\n");
    }

    private static void forgeMod(StringBuilder out, Context ctx) {
        out.append("import net.minecraftforge.common.MinecraftForge;\n");
        out.append("import net.minecraftforge.eventbus.api.SubscribeEvent;\n");
        out.append("import net.minecraftforge.fml.common.Mod;\n");
        out.append("import net.minecraftforge.fml.event.lifecycle.FMLCommonSetupEvent;\n");
        out.append("import net.minecraftforge.fml.javafmlmod.FMLJavaModLoadingContext;\n");
        out.append("import org.yonside.compat.api.CompatAddon;\n\n");

        out.append("@Mod(").append(literal(ctx.modId)).append(")\n");
        out.append("public final class ").append(ctx.modClass).append(" {\n\n");
        out.append("    private final CompatAddon addon = new ").append(ctx.addonClass).append("();\n\n");
        out.append("    public ").append(ctx.modClass).append("() {\n");
        out.append("        FMLJavaModLoadingContext.get().getModEventBus().register(this);\n");
        out.append("        MinecraftForge.EVENT_BUS.register(new ").append(ctx.listenerClass).append("(addon));\n");
        out.append("    }\n\n");
        out.append("    @SubscribeEvent\n");
        out.append("    public void init(FMLCommonSetupEvent event) {\n");
        out.append("        addon.onInit();\n");
        out.append("    }\n");
        out.append("}\n");
    }

    private static String listenerClass(Context ctx) {
        String subscribeEvent = switch (ctx.target.loader) {
            case CPW -> "cpw.mods.fml.common.eventhandler.SubscribeEvent";
            case FML -> "net.minecraftforge.fml.common.eventhandler.SubscribeEvent";
            case FORGE -> "net.minecraftforge.eventbus.api.SubscribeEvent";
        };
        StringBuilder out = new StringBuilder(ctx.header());
        out.append("import ").append(subscribeEvent).append(";\n");
        out.append("import net.minecraftforge.event.world.WorldEvent;\n");
        out.append("import org.yonside.compat.api.CompatAddon;\n");
        out.append("import org.yonside.compat.api.CompatWorld;\n\n");

        out.append("/** Forwards Forge-bus events to the addon. Compat Core's mixin makes every world a CompatWorld. */\n");
        out.append("public final class ").append(ctx.listenerClass).append(" {\n\n");
        out.append("    private final CompatAddon addon;\n\n");
        out.append("    public ").append(ctx.listenerClass).append("(CompatAddon addon) {\n");
        out.append("        this.addon = addon;\n");
        out.append("    }\n\n");
        out.append("    @SubscribeEvent\n");
        out.append("    public void onWorldLoad(WorldEvent.Load event) {\n");
        // 1.7.10's WorldEvent has a public field; later versions a getter.
        String world = ctx.target.loader == MinecraftTarget.Loader.CPW ? "event.world" : "event.getWorld()";
        out.append("        addon.onWorldLoad((CompatWorld) ").append(world).append(");\n");
        out.append("    }\n");
        out.append("}\n");
        return out.toString();
    }

    private static String simpleName(String internalName) {
        return internalName.substring(internalName.lastIndexOf('/') + 1).replace('$', '_');
    }

    /** JSON string escaping is also valid Java for everything that can appear here. */
    private static String literal(String value) {
        return MetadataRenderer.json(value);
    }
}
